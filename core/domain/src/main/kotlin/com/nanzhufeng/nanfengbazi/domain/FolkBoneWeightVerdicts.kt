/** 将四个七言式分句规整为等宽的上下两句，供当前评语与完整目录共用。 */
private fun String.asTwoLineCouplet(): String {
    val clauses = split(Regex("[，。、】【、！？；]+"))
        .filter { it.isNotBlank() }
    return if (clauses.size == 4) {
        "${clauses[0]}，${clauses[1]}。\n${clauses[2]}，${clauses[3]}。"
    } else {
        this
    }
}

